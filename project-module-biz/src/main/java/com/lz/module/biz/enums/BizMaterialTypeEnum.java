package com.lz.module.biz.enums;

import com.lz.framework.common.core.ArrayValuable;
import lombok.AllArgsConstructor;
import lombok.Getter;

import java.util.Arrays;

@Getter
@AllArgsConstructor
public enum BizMaterialTypeEnum implements ArrayValuable<String> {
    BIZ_MATERIAL_TYPE_0("0", "其他");

    public static final String[] ARRAYS = Arrays.stream(values()).map(BizMaterialTypeEnum::getStatus).toArray(String[]::new);

    /**
     * 状态值
     */
    private final String status;
    /**
     * 状态名
     */
    private final String name;

    @Override
    public String[] array() {
        return ARRAYS;
    }
}
